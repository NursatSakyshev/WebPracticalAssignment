const { isValidId, isPlainObject } = require('./common');

const MAX_NOTES_LENGTH = 2000;
const SERVER_FIELDS = ['id', 'created_at'];

function validateHunt(body, { partial = false } = {}) {
  if (!isPlainObject(body)) {
    return { errors: ['request body must be a JSON object (Content-Type: application/json)'] };
  }

  const allowed = partial ? ['success', 'notes'] : ['criminal_id', 'success', 'notes'];
  const errors = [];
  const data = {};

  for (const key of Object.keys(body)) {
    if (SERVER_FIELDS.includes(key)) {
      errors.push(`${key} is generated by the server and cannot be set`);
    } else if (partial && key === 'criminal_id') {
      errors.push('criminal_id cannot be changed');
    } else if (!allowed.includes(key)) {
      errors.push(`unknown field: ${key}`);
    }
  }

  if (!partial) {
    if (body.criminal_id === undefined) {
      errors.push('criminal_id is required');
    } else if (!isValidId(body.criminal_id)) {
      errors.push('criminal_id must be a positive integer');
    } else {
      data.criminal_id = body.criminal_id;
    }
  }

  if (body.success === undefined) {
    if (!partial) {
      errors.push('success is required');
    }
  } else if (typeof body.success !== 'boolean') {
    errors.push('success must be true or false');
  } else {
    data.success = body.success;
  }

  if (body.notes !== undefined) {
    if (body.notes !== null && typeof body.notes !== 'string') {
      errors.push('notes must be a string');
    } else if (typeof body.notes === 'string' && body.notes.length > MAX_NOTES_LENGTH) {
      errors.push(`notes must be at most ${MAX_NOTES_LENGTH} characters`);
    } else {
      data.notes = body.notes === null ? null : body.notes.trim() || null;
    }
  }

  if (partial && errors.length === 0 && Object.keys(data).length === 0) {
    errors.push('at least one of success, notes must be provided');
  }

  return { errors, data };
}

function parseHuntQuery(query) {
  const errors = [];
  const filters = {};

  if (query.criminal_id !== undefined) {
    const value = query.criminal_id;
    const n = Number(value);
    if (typeof value !== 'string' || !/^\d+$/.test(value) || !isValidId(n)) {
      errors.push('criminal_id must be a positive integer');
    } else {
      filters.criminal_id = n;
    }
  }

  return { errors, filters };
}

module.exports = { validateHunt, parseHuntQuery };
